    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:

        try {
            // Create a file chooser for selecting images
            JFileChooser picChooser = new JFileChooser();
            FileNameExtensionFilter filter = new FileNameExtensionFilter("Images", "png", "jpg");
            picChooser.addChoosableFileFilter(filter);

            // Open file chooser dialog
            int returnValue = picChooser.showOpenDialog(null);

            // If the user selects an image
            if (returnValue == JFileChooser.APPROVE_OPTION) {
                File pic = picChooser.getSelectedFile();  // Get selected file
                String path = pic.getAbsolutePath();  // Get file path

                // Read the image as BufferedImage and scale it
                BufferedImage img = ImageIO.read(pic);
                ImageIcon imageIcon = new ImageIcon(img.getScaledInstance(250, 250, Image.SCALE_DEFAULT));

                // Assuming txtphoto is a JLabel for displaying the image
                txtphoto.setIcon(imageIcon);

                // Convert the image to a byte array for storing in the database
                File image = new File(path);
                FileInputStream fis = new FileInputStream(image);
                ByteArrayOutputStream baos = new ByteArrayOutputStream();
                byte[] buff = new byte[1024];
                for (int readNum; (readNum = fis.read(buff)) != -1;) {
                    baos.write(buff, 0, readNum);
                }
                userimage = baos.toByteArray();  // Assign the byte array to userimage
            } else {
                System.out.println("No file selected.");
            }
        } catch (IOException ex) {
            Logger.getLogger(AddCustomer.class.getName()).log(Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "Failed to load image!", "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton3ActionPerformed

